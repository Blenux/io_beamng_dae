def _context_bng_node(context):
    """Find the BeamNG node for the current UI context.

    Node editor → context.active_node; node buttons drawn in the Properties
    editor → context.node; otherwise fall back to the active material's tree.
    """
    for attr in ('active_node', 'node'):
        node = getattr(context, attr, None)
        if node is not None and node.bl_idname == 'ShaderNodeBeamngMaterial':
            return node
    mat = getattr(context, 'material', None)
    if mat is not None and mat.use_nodes and mat.node_tree is not None:
        for n in mat.node_tree.nodes:
            if n.bl_idname == 'ShaderNodeBeamngMaterial':
                return n
    return None


class NODE_OT_bng_add_layer(bpy.types.Operator):
    """Add a layer to the BeamNG Material node"""
    bl_idname = "node.bng_add_layer"
    bl_label = "Add Layer"

    @classmethod
    def poll(cls, context):
        return _context_bng_node(context) is not None

    def execute(self, context):
        node = _context_bng_node(context)
        if node is not None and node.bng_active_layers < 4:
            node.bng_active_layers += 1
        return {'FINISHED'}


class NODE_OT_bng_remove_layer(bpy.types.Operator):
    """Remove the last layer from the BeamNG Material node"""
    bl_idname = "node.bng_remove_layer"
    bl_label = "Remove Layer"

    @classmethod
    def poll(cls, context):
        return _context_bng_node(context) is not None

    def execute(self, context):
        node = _context_bng_node(context)
        if node is not None and node.bng_active_layers > 1:
            node.bng_active_layers -= 1
        return {'FINISHED'}


class NODE_OT_bng_move_layer(bpy.types.Operator):
    """Move a layer up or down in the BeamNG Material node"""
    bl_idname = "node.bng_move_layer"
    bl_label = "Move Layer"

    index: IntProperty()
    direction: IntProperty()  # -1 = up, +1 = down

    @classmethod
    def poll(cls, context):
        return _context_bng_node(context) is not None

    def execute(self, context):
        node = _context_bng_node(context)
        if node is None:
            return {'CANCELLED'}
        target = self.index + self.direction
        if 0 <= target < node.bng_active_layers:
            node.stages.move(self.index, target)
            node._rebuild()
        return {'FINISHED'}


class NODE_OT_bng_compile_to_nodes(bpy.types.Operator):
    """Expand the BeamNG material into standard Blender shader nodes
    inside the material's node tree (mirrors NODE_OT_bng_compile_to_nodes)."""
    bl_idname = "node.bng_compile_to_nodes"
    bl_label = "Compile to Blender Nodes"

    @classmethod
    def poll(cls, context):
        return _context_bng_node(context) is not None

    def execute(self, context):
        node = _context_bng_node(context)
        if node is None:
            return {'CANCELLED'}
        from . import beamng_material_graph
        beamng_material_graph.compile_to_material_tree(node)
        return {'FINISHED'}


