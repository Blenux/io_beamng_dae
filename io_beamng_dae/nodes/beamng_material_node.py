    def _rebuild(self):
        """Regenerate the internal node group (gpu_fn equivalent)."""
        if self.is_rebuilding:
            return
        self.is_rebuilding = True
        try:
            from . import beamng_material_graph
            beamng_material_graph.build_graph(self)
        finally:
            self.is_rebuilding = False

    def _get_or_create_tree(self):
        """Unique node group per material — a shared group would let
        nodes.clear() wipe every material's internal graph. Leading '.'
        hides the group from the Add→Group menu / link-drag search."""
        if self.node_tree is None:
            mat_name = ""
            id_data = self.id_data
            if id_data is not None and hasattr(id_data, "nodes") \
                    and not hasattr(id_data, "blend_method"):
                # id_data is the containing NodeTree — find its Material.
                for m in bpy.data.materials:
                    if m.node_tree == id_data:
                        mat_name = m.name
                        break
            elif id_data is not None:
                mat_name = getattr(id_data, "name", "")
            group_name = (f".{NODE_GROUP_NAME} ({mat_name})" if mat_name
                          else f".{NODE_GROUP_NAME}")
            self.node_tree = bpy.data.node_groups.new(
                group_name, 'ShaderNodeTree')
        elif not self.node_tree.name.startswith('.'):
            # Migrate groups created before the hidden-name convention.
            self.node_tree.name = '.' + self.node_tree.name
        return self.node_tree

    def get_stage(self, index):
        if 0 <= index < len(self.stages):
            return self.stages[index]
        return None


