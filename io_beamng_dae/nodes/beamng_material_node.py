def _img_prop(field, label):
    """Image pointer prop wired to its path string + colorspace sync."""
    return PointerProperty(
        name=label, type=bpy.types.Image, update=_img_update(field))


def _path_prop(label, desc=""):
    return StringProperty(name=label, default="", description=desc,
                          update=_stage_update)


def _uv_prop(label):
    return IntProperty(name=label, default=0, min=0, max=3,
                       update=_stage_update)


def _fac_prop(label, default, lo=0.0, hi=1.0):
    return FloatProperty(name=label, default=default, min=lo, max=hi,
                         update=_stage_update)


def _bool_prop(label, default=False):
    return BoolProperty(name=label, default=default, update=_stage_update)


