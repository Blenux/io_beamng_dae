"""BeamNG Material node — mirrors the BeamNGer fork's ShaderNodeBeamngMaterial
(source/blender/nodes/shader/nodes/node_shader_beamng_material.cc).

Design:
- One node = one BeamNG material (matches the game's single Material concept).
- All state lives on the node as bpy.props, mirroring the fork's
  NodeShaderBeamngMaterial / NodeShaderBeamngMaterialStage DNA structs.
  Stage fields use the fork's DNA names verbatim (color_map, normal_map, ...)
  inside BeamNGStageSlot — bng_stage{i}_<field> in fork RNA maps to
  node.stages[i].<field>.
- Vehicle paints live on Scene.bng_vehicle_paints (single source of truth),
  matching the fork's BeamNGVehiclePaints — see core/paints.py.
- The internal node group is generated by beamng_material_graph.build_graph(),
  a Python port of the fork's gpu_beamng_material() compile.
- Material flag sync mirrors beamng_material_sync.cc.
- Unknown JSON keys round-trip via extra_json (lossless).
"""

import bpy
from bpy.props import (
    StringProperty,
    BoolProperty,
    FloatProperty,
    FloatVectorProperty,
    IntProperty,
    EnumProperty,
    PointerProperty,
    CollectionProperty,
)
from bpy.types import PropertyGroup


# ---------------------------------------------------------------------------
# Update callback helpers
# ---------------------------------------------------------------------------

def _find_bng_node(self):
    """Find the ShaderNodeBeamngMaterial node from a PropertyGroup or node."""
    if hasattr(self, 'node_tree') and self.node_tree is not None:
        return self
    id_data = getattr(self, 'id_data', None)
    if id_data is not None:
        # id_data is a material with a node_tree
        if hasattr(id_data, 'node_tree') and id_data.node_tree is not None:
            for n in id_data.node_tree.nodes:
                if n.bl_idname == 'ShaderNodeBeamngMaterial':
                    return n
        # id_data is a node tree directly
        if hasattr(id_data, 'nodes'):
            for n in id_data.nodes:
                if n.bl_idname == 'ShaderNodeBeamngMaterial':
                    return n
    return None


def _stage_update(self, context):
    """Rebuild internal graph when a stage property changes."""
    if getattr(self, 'is_rebuilding', False):
        return
    node = _find_bng_node(self)
    if node is not None and not node.is_rebuilding:
        node._rebuild()


def _global_update(self, context):
    """Rebuild internal graph + sync material flags (rna_Node_update equivalent)."""
    node = self if hasattr(self, 'node_tree') else _find_bng_node(self)
    if node is not None and not node.is_rebuilding:
        node._rebuild()
        _sync_material_flags(node)


def _flag_update(self, context):
    """rna_BeamngMaterial_update equivalent — same work as _global_update."""
    _global_update(self, context)


def _img_update(field_name):
    """Create an update callback for an image pointer property.

    Mirrors the fork's bng_sync_path_from_image() + bng_image_set_colorspace_from_field():
    assigning an Image copies its filepath into the matching path string field
    and sets the image color space from the BeamNG suffix convention.
    """
    def _update(self, context):
        img = getattr(self, field_name + '_img')
        node = _find_bng_node(self)
        batch = node is not None and getattr(node, 'is_rebuilding', False)
        if img is not None:
            # Batch populate keeps the original BeamNG path string;
            # user UI assignment syncs the resolved filepath (fork parity).
            if not batch:
                setattr(self, field_name, img.filepath or img.name)
            from ..core.materials_library import is_srgb_texture
            try:
                img.colorspace_settings.name = (
                    'sRGB' if is_srgb_texture(img.filepath or img.name)
                    else 'Non-Color'
                )
            except TypeError:
                pass  # colorspace name unavailable in this Blender build
        _stage_update(self, context)
    return _update


def _sync_material_flags(node):
    """Sync Blender material settings from BeamNG node flags.

    Mirrors beamng_material_sync.cc::beamng_sync_material_flags:
    - translucent + alpha_blend_mode > 0 → Blended (FORWARD)
    - alpha_test → Dithered (DEFERRED) + alpha_threshold = alpha_ref/255
    - otherwise → Dithered opaque
    - cast_shadows → blend_shadow SOLID/NONE (4.x only; removed in 5.x)
    - double_sided → use_backface_culling inverted
    """
    mat = node.id_data
    if mat is None:
        return
    # If id_data is a node tree (not a material), find the material using it
    if hasattr(mat, "nodes") and not hasattr(mat, "blend_method"):
        for m in bpy.data.materials:
            if m.node_tree == mat:
                mat = m
                break
        else:
            return
    if not hasattr(mat, "blend_method"):
        return

    has_srm = hasattr(mat, 'surface_render_method')
    blend_active = node.bng_translucent and node.bng_alpha_blend_mode != 'NONE'
    if blend_active:
        # translucentZWrite=true → depth-writing hashed transparency
        # (DITHERED/deferred); false → sorted forward blend (BLENDED).
        # Cycles ignores render_method — BSDF Alpha drives it there.
        if has_srm:
            mat.surface_render_method = \
                'DITHERED' if node.bng_z_write else 'BLENDED'
        else:
            mat.blend_method = "BLEND"
        if node.bng_alpha_test:
            mat.alpha_threshold = node.bng_alpha_ref / 255.0
    elif node.bng_alpha_test:
        if has_srm:
            mat.surface_render_method = 'DITHERED'
        else:
            mat.blend_method = "CLIP"
        mat.alpha_threshold = node.bng_alpha_ref / 255.0
    else:
        if has_srm:
            mat.surface_render_method = 'DITHERED'
        else:
            mat.blend_method = "OPAQUE"

    mat.use_backface_culling = not node.bng_double_sided

    # Transparency sorting: hide backfaces inside transparent regions
    # unless the material is double-sided (glass needs both).
    if hasattr(mat, 'use_transparency_overlap'):
        mat.use_transparency_overlap = not node.bng_double_sided

    # Shadows: BeamNG uses binary depth-only shadows — opaque shadow
    # casting for opaque mats, transparent-shadow only when alpha-test
    # or translucent would otherwise produce square shadows.
    if hasattr(mat, 'use_transparent_shadow'):
        mat.use_transparent_shadow = (
            blend_active or node.bng_alpha_test) and node.bng_cast_shadows
    if hasattr(mat, 'use_backface_culling_shadow'):
        mat.use_backface_culling_shadow = node.bng_cast_shadows \
            and not node.bng_double_sided
    if hasattr(mat, 'blend_shadow'):
        mat.blend_shadow = 'SOLID' if node.bng_cast_shadows else 'NONE'


def sync_all_material_flags():
    """Re-sync material flags on every material containing a BeamNG node.

    Mirrors beamng_material_sync.cc::beamng_sync_all_material_flags."""
    for mat in bpy.data.materials:
        if not mat.use_nodes or mat.node_tree is None:
            continue
        for n in mat.node_tree.nodes:
            if n.bl_idname == 'ShaderNodeBeamngMaterial':
                _sync_material_flags(n)
                break


